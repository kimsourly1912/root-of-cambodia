import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
import {createTestHarness} from "wrangler";
import {getMigrations} from "better-auth/db/migration";
import {makeAuth,emailFixtureSQL} from "../src/auth";
import {migrate,fixture} from "./support";
const baseURL="http://127.0.0.1:8787";
const server=createTestHarness({workers:[{configPath:"wrangler.jsonc",secrets:{BETTER_AUTH_SECRET:randomBytes(32).toString("hex")}}]});
const passed:string[]=[];
const check=(name:string)=>{passed.push(name);console.log("PASS "+name);};
const post=(path:string,body:unknown,cookie?:string,origin=baseURL,ip="192.0.2.10")=>server.fetch(baseURL+path,{method:"POST",headers:{"Content-Type":"application/json",Origin:origin,"CF-Connecting-IP":ip,...(cookie?{Cookie:cookie}:{})},body:JSON.stringify(body),redirect:"manual"});
try {
  await server.listen();
  const first=await server.fetch(baseURL);
  assert.equal(first.status,200);
  assert.ok((await first.text()).includes("ការកក់កន្លែងស្នាក់នៅ"));
  check("Upstream Next.js SSR under local workerd");
  const env=await server.getWorker<CloudflareEnv>().getEnv();
  const db=env.DB;
  const auth=makeAuth(db,{secret:env.BETTER_AUTH_SECRET,baseURL,mode:"local"});
  const migrations=await getMigrations(auth.options); await migrations.runMigrations();
  await db.prepare(emailFixtureSQL).run();
  await migrate(db); await fixture(db);
  const anonymous=await server.fetch(baseURL+"/api/session");
  assert.deepEqual(await anonymous.json(),{authenticated:false,verified:false});
  assert.ok(anonymous.headers.get("cache-control")?.includes("no-store"));
  check("Anonymous session endpoint is private/no-store");
  const password="LocalOnly-WorkerPassword-123!";
  async function account(label:string,ip:string){
    const email=label+"-"+Date.now()+"@example.invalid";
    const signup=await post("/api/auth/sign-up/email",{name:label,email,password},undefined,baseURL,ip);
    assert.equal(signup.status,200,"Signup must work on workerd");
    const data=await signup.json() as {user:{id:string}};
    assert.equal((await post("/api/auth/sign-in/email",{email,password},undefined,baseURL,ip)).status,403,"Unverified login must be rejected");
    const message=await db.prepare("SELECT url FROM proof_email WHERE recipient=? AND kind='verify' LIMIT 1").bind(email).first<{url:string}>();
    assert.ok(message,"Verification must be delivered to local capture adapter");
    assert.equal((await server.fetch(message.url,{redirect:"manual",headers:{"CF-Connecting-IP":ip}})).status,302);
    const login=await post("/api/auth/sign-in/email",{email,password},undefined,baseURL,ip);
    assert.equal(login.status,200);
    const cookie=login.headers.getSetCookie().map(x=>x.split(";")[0]).join("; ");
    assert.ok(cookie);
    return {id:data.user.id,cookie,email};
  }
  const owner=await account("owner","192.0.2.10");
  check("Email/password signup, verification, and cookie login under workerd");
  const session=await server.fetch(baseURL+"/api/session",{headers:{Cookie:owner.cookie}});
  assert.deepEqual(await session.json(),{authenticated:true,verified:true});
  check("Verified cookie session reaches Next.js server route");
  await db.prepare("UPDATE property SET owner_id=? WHERE id='p'").bind(owner.id).run();
  assert.equal((await post("/api/bookings/a/accept",{})).status,401);
  assert.equal((await post("/api/bookings/a/accept",{},owner.cookie,"https://untrusted.example.invalid")).status,403);
  check("Unauthenticated and cross-origin booking mutations rejected");
  const results=await Promise.all(["a","b"].map(id=>post("/api/bookings/"+id+"/accept",{},owner.cookie)));
  assert.deepEqual(results.map(r=>r.status).sort(),[200,409]);
  const inventory=await db.prepare("SELECT reserved FROM inventory_night").all<{reserved:number}>();
  assert.deepEqual(inventory.results.map(x=>x.reserved),[1,1]);
  check("HTTP race: one confirmation and one conflict for the last room");
  const other=await account("other-owner","192.0.2.20");
  assert.equal((await post("/api/bookings/a/accept",{ownerId:owner.id,emailVerified:true},other.cookie)).status,404);
  check("Another account cannot impersonate the property owner");
  const reset=await post("/api/auth/request-password-reset",{email:owner.email,redirectTo:baseURL+"/reset-password"},undefined,baseURL,"192.0.2.30");
  assert.equal(reset.status,200);
  const resetMessage=await db.prepare("SELECT url FROM proof_email WHERE recipient=? AND kind='reset' LIMIT 1").bind(owner.email).first<{url:string}>();
  assert.ok(resetMessage);
  const token=new URL(resetMessage.url).pathname.split("/").at(-1);
  const newPassword="LocalOnly-WorkerChanged-456!";
  assert.equal((await post("/api/auth/reset-password",{token,newPassword},undefined,baseURL,"192.0.2.30")).status,200);
  assert.equal((await post("/api/auth/sign-in/email",{email:owner.email,password},undefined,baseURL,"192.0.2.30")).status,401);
  assert.equal((await post("/api/auth/sign-in/email",{email:owner.email,password:newPassword},undefined,baseURL,"192.0.2.30")).status,200);
  check("Password reset and changed credential under workerd");
  const attempts=[];
  for(let i=0;i<4;i++) attempts.push(await post("/api/auth/sign-in/email",{email:owner.email,password:"Wrong-Local-Password"},undefined,baseURL,"192.0.2.99"));
  assert.equal(attempts.at(-1)?.status,429);
  check("Rate limiting stays enabled for repeated failed authentication");
  console.log(JSON.stringify({checks:passed.length,result:"passed",runtime:"local workerd",email:"test capture only"}));
}catch(error){
  console.error("Worker harness failed; no email tokens are printed.");
  throw error;
}finally{
  await server.close();
}
